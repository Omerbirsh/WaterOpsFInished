function translateParameter(value: string) {
  const normalized = value.trim().toLowerCase()
  const match = Object.entries(parameterTranslations).find(([parameter]) => parameter.toLowerCase() === normalized)
  return match?.[1] ?? value
}

function isFeminineParameter(value: string) {
  return ["Conductivity", "Inhibitor residual", "Oxidant residual", "Sulfite residual", "Nitrite residual"].includes(value)
}

function formatHebrewDate(month: string, day: string, year?: string) {
  const date = new Date(Date.UTC(Number(year ?? "2026"), monthNumbers[month], Number(day)))
  return new Intl.DateTimeFormat("he-IL", {
    day: "numeric",
    month: year ? "long" : "short",
    ...(year ? { year: "numeric" as const } : {}),
    timeZone: "UTC",
  }).format(date)
}

